def _is_host_port(peer: str) -> bool:
    """True if `peer` looks like ``host:port`` with a usable port."""
    host, sep, port = peer.rpartition(":")
    return bool(sep and host and port.isdigit() and 0 < int(port) < 65536)


def _peer_api_key(server: dict) -> str | None:
    """The MCP bearer key for one ``mcp.client.remote_servers`` entry.

    None for anything unusable, INCLUDING a value that still contains "${".
    A planner whose config was never regenerated by this orchestrator falls
    back to the source template, where the value is the literal
    "${mcp_api_key}" — sending that as a bearer token turns every connect into
    a 401 that reads like a wrong key rather than an ungenerated config, and it
    would put a template placeholder in the peer's auth-rejection log. The
    dashboard's chat_service rejects the same shape for the llama key.
    """
    value = server.get("api_key")
    if not isinstance(value, str) or not value.strip() or "${" in value:
        return None
    return value.strip()


def _expected_rpc_proto(path: str | None = None) -> tuple[int, int] | None:
    """(major, minor) of the RPC protocol this image's llama.cpp speaks, or None.

    None when the build record is absent, unreadable or carries no
    ``rpc_proto`` (images built before the key existed): the peer wait then
    still requires a HELLO reply but compares nothing, so an old image is not
    refused by a check it cannot pass. The path is resolved at call time, not
    bound as a default, so the module constant stays the single source.
    """
    try:
        data = json.loads(Path(path or _LLAMA_BUILD_JSON).read_text(encoding="utf-8"))
        major, minor, *_rest = str(data["rpc_proto"]).split(".")
        return int(major), int(minor)
    except (OSError, ValueError, KeyError, TypeError):
        return None


def _recv_exact(sock: socket.socket, n: int) -> bytes | None:
    """Read exactly n bytes, or None on EOF or timeout."""
    buf = bytearray()
    while len(buf) < n:
        try:
            chunk = sock.recv(n - len(buf))
        except OSError:
            return None
        if not chunk:
            return None
        buf += chunk
    return bytes(buf)


def _exit_status(rc: int | None) -> int:
    """Map a Popen return code to a process exit status.

    Popen reports a signal death as a NEGATIVE number, and ``sys.exit(-9)``
    wraps to 247 — so a SIGKILLed child surfaced in `kubectl describe` as an
    exit code nobody recognises, instead of the conventional 137.
    """
    if rc is None:
        return 0
    return 128 - rc if rc < 0 else rc


# Fixed cap on the child's log file, which lives on a hostPath volume and
# would otherwise grow for the lifetime of the node (llama-server logs every
# request). The `logging.max_file_size_mb`/`max_files` config knobs are
# reserved but unimplemented — this cap is deliberately not configurable.
_CHILD_LOG_MAX_BYTES = 100 * 1024 * 1024

# How long _reap_stale_children waits for a SIGKILLed orphan to actually leave
# the process table. Generous: the wait only runs when an orphan was found, and
# a llama-server unmapping a multi-GB model measured 25ms at 2GB, so 10s is a
# ceiling nothing legitimate reaches — and it sits far inside the 3015s edge
# startupProbe budget.
_REAP_WAIT_SECONDS = 10.0

# Where the deployer installs a shard worker's tensor-cache manifest: the list
# of every tensor over rpc-server's 10 MiB cache threshold in the group's
# model, as content hash (the cache file name) and byte size. Produced on the
# orchestrator by scripts/seed-rpc-cache.py from the GGUF header, so a worker
# can tell a weight it should keep from a file it should not — see
# AureaxClient._audit_rpc_cache. Absent on a node whose model was never
# manifested; the audit then reports and deletes nothing.
_RPC_CACHE_MANIFEST = "/etc/aureax/rpc-cache-manifest.json"

# llama.cpp's RPC handshake, as read from ggml-rpc.cpp at ba360efe / b10375
# (RPC protocol 5.0.0; the pinned b11429 speaks 7.0.0, so heads and workers
# must be rebuilt together, and this layout was not re-read at the new pin):
# a connection MUST open with HELLO, command 14 — one byte
# of command, a little-endian u64 payload size of 24, then 24 bytes of
# connection capabilities (all zero here: no RDMA). The reply is a
# little-endian u64 size of 28 followed by major, minor, patch, one pad byte
# and 24 capability bytes. The server closes a connection whose first byte is
# anything else, and llama-server refuses a peer whose major differs or whose
# minor is newer. The head's peer wait sends exactly this exchange (see
# AureaxClient._rpc_hello) so "the worker is listening" becomes "the worker
# speaks our protocol version" — the difference between a 300 s timeout
# followed by an RPC-handshake hang and a named failure in under a second.
_RPC_CMD_HELLO = 14
_RPC_CONN_CAPS_SIZE = 24
_RPC_HELLO_REPLY_SIZE = 4 + _RPC_CONN_CAPS_SIZE

# The image's build record, written by both Dockerfiles. {"version", "commit"}
# on every image; images built after the engine upgrade also carry
# "rpc_proto" ("<major>.<minor>.<patch>", read out of ggml-rpc.h at build
# time), which is what the peer wait compares a worker's HELLO reply against.
# Absent key = no comparison, only a log line naming what the worker said.
_LLAMA_BUILD_JSON = "/usr/local/share/aureax-llama-build.json"

# How long a shard worker waits for its own rpc-server to accept connections.
# Ample, because rpc-server binds its listener at startup and does no loading
# first (client/config/parser.py::get_rpc_server_args passes no model).
#
# It stays under daemonset-shard.yaml's startupProbe budget (5 + 24x5 = 125s)
# so the WAIT ends first and the failure leaves through the supervisor's own
# _exit_reporting — the only path that ships a crash context off a worker —
# instead of a silent kubelet restart. What _exit_reporting then does (the
# child wait, then the log drain) runs past the probe deadline and is covered
# by terminationGracePeriodSeconds, not by the 5s of headroom left here.
_RPC_LISTEN_TIMEOUT = 120


class _CappedLogFile:
    """Append sink for the child log that rotates once at a fixed size.

    On hitting the cap the current file replaces ``<name>.1`` and a fresh
    file is started, so the node keeps at most ~2x the cap on disk while the
    most recent output — the part that explains a crash — is always present.
    """

    def __init__(self, path: Path, max_bytes: int = _CHILD_LOG_MAX_BYTES) -> None:
        self._path = path
        self._max = max_bytes
        self._f = path.open("a")
        self._size = self._f.tell()
        # Sticky across the failure streak, not across the process: _rotate is
        # re-entered on every write once _f is None, and one warning per line
        # would be its own outage. Cleared on a successful reopen so a later
        # re-failure is still visible.
        self._degraded = False
        # close() is final: the pump thread can still be draining the child's
        # last lines when stop() closes the FD under it, and the retry below
        # must not resurrect a file the supervisor is done with.
        self._closed = False

    def write(self, s: str) -> None:
        if self._closed:
            return
        if self._f is None and not self._reopen():
            return  # sink is degraded; the stdout tee still carries the line
        try:
            self._f.write(s)
            # len() counts characters, not bytes — llama.cpp output is ASCII,
            # and an off-by-a-few-percent cap is fine.
            self._size += len(s)
        except OSError:
            # ENOSPC/EROFS lands here as readily as in _rotate, and
            # _pump_child_output suppresses OSError — so an escape ends the file
            # sink for the pod's life with nothing said: _size never advances,
            # so _rotate, the only other path that degrades loudly, is never
            # reached. Drop the file object instead, warn once, and let the next
            # write retry through _reopen().
            with contextlib.suppress(OSError):
                self._f.close()
            self._f = None
            if not self._degraded:
                self._degraded = True
                logger.warning("Child log sink degraded — cannot write to %s", self._path)
            return
        if self._size >= self._max:
            self._rotate()

    def _reopen(self) -> bool:
        """Reopen the sink after a failed rotation. True if it is usable again."""
        try:
            self._f = self._path.open("a")
        except OSError:
            return False
        # MUST reset: _size still carries the pre-rotation total, so leaving it
        # >= _max makes the very next write rotate again — one close/replace
        # per line, each clobbering the .1 archive.
        self._size = self._f.tell()
        self._degraded = False
        return True

    def _rotate(self) -> None:
        # close() flushes, so on a full disk it is the FIRST call here to raise
        # — and an escape would skip the reopen/degrade below entirely, leaving
        # a closed file object in _f that every later write trips over. Suppress
        # so _rotate always reaches its recovery path.
        with contextlib.suppress(OSError):
            self._f.close()
        with contextlib.suppress(OSError):
            self._path.replace(self._path.with_name(self._path.name + ".1"))
        self._f = None
        self._size = 0
        # The cap is hit when the hostPath disk is most likely full, so this
        # reopen is exactly where ENOSPC/EROFS lands. _pump_child_output
        # suppresses OSError, so an escape here would silently end the file
        # sink for the pod's life; degrade to one lost line and retry next
        # write.
        if not self._reopen() and not self._degraded:
            self._degraded = True
            logger.warning("Child log sink degraded — cannot reopen %s", self._path)

    def flush(self) -> None:
        if self._f is not None:
            self._f.flush()

    def close(self) -> None:
        self._closed = True
        if self._f is not None:
            self._f.close()
            self._f = None


class AureaxClient:
    """Process supervisor for the edge client."""

    def __init__(self, config_path: str = "/etc/aureax/aureax-edge.yaml") -> None:
        """Load edge config and prepare process state."""
        self.config = load_edge_config_raw(config_path)
        self.node_id = self.config["node"]["id"]
        # The single managed inference child. Which binary it is depends on the
        # node's role: llama-server on a standalone/head node, rpc-server on a
        # shard worker. stop() tears down whichever one was spawned.
        self._child_proc: subprocess.Popen | None = None
        self._child_name = "llama-server"
        self._child_log_file = None
        self._child_log_thread: threading.Thread | None = None
        self._shutdown = False
        self._telemetry_thread: threading.Thread | None = None
        self.telemetry_storage: TelemetryStorage | None = None

        # Local log buffer + shipper. Both stay None when logging.ship_logs is
        # off, and every use site is guarded, so a node that opts out behaves
        # exactly as before.
        self._log_store = None
        self._log_reporter = None
        self._child_capture = None
        self._log_thread = None
        self._init_log_store()
        self._init_log_reporter()

    def start(self) -> None:
        """Start all managed services.

        If a llama-server is already listening on the configured port (e.g.
        one launched by a sidecar or external supervisor), reuse it instead
        of spawning our own.
        """
        # FIRST, before the signal handlers and before the shard-worker branch:
        # every listener and every client on this node is TLS-only, so a node
        # with no certificates is a node that cannot serve, not one that serves
        # differently.
        self._require_tls_files()

        logger.info("Starting aureax-client for node %s", self.node_id)

        # Register signal handlers
        signal.signal(signal.SIGTERM, self._handle_signal)
        signal.signal(signal.SIGINT, self._handle_signal)

        # Branch before ANY llama-server logic: a shard worker runs rpc-server
        # and serves no HTTP, so the health wait below would spawn a pointless
        # llama-server and then sys.exit(1) when /health never answers.
        if self._shard_role() == SHARD_WORKER_ROLE:
            self._run_shard_worker()
            return

        # Telemetry first, deliberately. A sharded head can spend 15 minutes
        # between here and a healthy /health — waiting for peers, then streaming
        # every tensor to them — and starting telemetry afterwards means the node
        # reports nothing at all for that entire window, and nothing ever if the
        # load fails. That window is exactly when an operator is watching.
        # collect_all tolerates a llama-server that isn't up yet.
        self._start_telemetry()
        self._start_log_shipping()

        # Reap BEFORE probing the port, not only on the spawn path. An orphaned
        # llama-server from a previous pod is exactly what holds this port —
        # llama.cpp accepts connections while still loading, and the DaemonSet
        # runs hostNetwork, so without this reap the probe below sees the orphan
        # and takes the attach branch, leaving the pod reporting Ready in front
        # of a wedged server it has no handle to kill.
        survivors = self._reap_stale_children(
            os.environ.get("LLAMA_SERVER_PATH", "llama-server")
        )
        if survivors:
            # BEFORE the peer wait, not after: neither branch below can proceed,
            # so waiting up to node.worker_wait_timeout_seconds first only delays
            # the same failure by five minutes. A recorded child that is still
            # owned by a live supervisor, or that outlived its SIGKILL, is still
            # holding this port under hostNetwork — attaching would front a
            # process this supervisor has no handle on, and spawning would fail
            # to bind. Exit through the reporting path so the crash context and
            # the pending logs reach the orchestrator.
            logger.error(
                "A previously managed llama-server is still active (pid(s) %s) — refusing "
                "to attach to it or to spawn a second one",
                survivors,
            )
            self._exit_reporting(1)

        if self._llama_port_in_use():
            # An attached server keeps whatever LLAMA_API_KEY it was started
            # with. The in-pod clients still send the header from THIS config,
            # so a mismatch surfaces as loud 401s (the collector ships a
            # one-shot error) rather than silence — and the one mismatch that
            # would be silent, a server enforcing no key at all, is what
            # _refuse_unauthenticated_attach checks once /health answers.
            logger.info("llama-server already running on port %d — attaching "
                        "(its API-key auth state is whatever it started with)",
                        self._llama_port())
            # Health-check the attached server too. Anything can hold this port
            # — a half-loaded server, an unrelated service — and on this branch
            # _child_proc stays None, so no exit path can ever fire: without
            # this the pod fronts a corpse until the 3015s startupProbe budget
            # runs out. The wait's own timeout exits through _exit_reporting,
            # which restarts the pod with the crash context shipped.
            self._wait_for_llama_health()
            self._refuse_unauthenticated_attach()
        else:
            self._wait_for_rpc_workers()
            self._start_llama_server()
            self._wait_for_llama_health()

        # After /health, on both branches: a healthy sharded head can still be
        # serving a topology nobody configured, and every other signal in the
        # stack is green while it does.
        self._verify_rpc_topology()

        # Branch on MCP mode (per ARCHITECTURE.md section 5, "Process
        # Management Architecture": the supervisor owns either an MCP server or
        # an mcp-client/host runtime — in-process here, not as a child).
        mcp_cfg = self.config.get("mcp") or {}
        client_enabled = (mcp_cfg.get("client") or {}).get("enabled", False)
        server_enabled = (mcp_cfg.get("server") or {}).get("enabled", True)

        if client_enabled:
            self._start_planner()  # cognitive-planner pod: connect to remotes, idle
        elif server_enabled:
            self._start_mcp_server()  # edge pod: blocks running FastMCP
        else:
            # Without a blocking MCP runtime this method would return, PID 1
            # would exit 0, and K8s would tear down a pod whose llama-server
            # was serving fine. Supervise the child instead, like a worker.
            logger.warning(
                "Both mcp.client and mcp.server are disabled — no MCP runtime; "
                "supervising llama-server until it exits"
            )
            self._block_on_child()

    def _require_tls_files(self) -> None:
        """Exit 78 unless this node's three TLS files are present and readable.

        Called from start(), not __init__: __init__ is what tests/conftest.py's
        ``bare_client`` fixture bypasses and what a local dev run constructs, so
        a filesystem requirement there breaks both without buying anything —
        nothing has been served yet at that point.

        Applies to shard workers too, even though rpc-server takes no
        certificate: a worker still ships telemetry and logs to the
        orchestrator over TLS and so needs ``ca_file``, and the deployer
        installs all three files in one command, so a worker missing its cert
        or key means that push was broken. A uniform rule has no branch to get
        wrong.

        78 is EX_CONFIG from sysexits.h (client/tls.py) — distinct from the
        generic 1, from the 137 an OOM-killed load produces, and from every
        code _exit_status maps a child's death onto, so `kubectl describe`
        names the cause. Exits directly rather than through _exit_reporting:
        nothing has been started yet, so there is no child to tear down and no
        crash context to ship, and the log shipper itself needs the CA.
        """
        try:
            require_tls_files(self.config)
        except (ValueError, FileNotFoundError) as e:
            logger.error(
                "TLS material missing on this node: %s. The orchestrator installs "
                "/etc/aureax/tls/{ca.pem,node.pem,node.key} with the config — run "
                "`aureax apply --node %s` from the Mac. Refusing to start unencrypted.",
                e, self.node_id,
            )
            sys.exit(EX_CONFIG)

    def _tls_context(self) -> ssl.SSLContext:
        """The fleet-CA SSLContext every in-pod httpx client passes as ``verify=``.

        Called per client rather than stored on the instance: ssl_context()
        caches per CA file (client/tls.py), so repeat calls are a dict lookup.
        __init__ does only best-effort, exception-guarded filesystem work — it
        reaches this method through _init_log_reporter — and any HARD filesystem
        requirement belongs in start()'s _require_tls_files instead, for the
        reason that method documents.
        """
        return ssl_context(self.config)

    def _tls_cert_and_key(self) -> tuple[str, str]:
        """``(cert_file, key_file)`` for this node's own listeners."""
        _ca, cert, key = tls_paths(self.config)
        return cert, key

    def _llama_server_cfg(self) -> dict:
        """``model.server`` as a dict, whatever the YAML left behind.

        ``or {}`` at BOTH levels, not a plain ``.get(..., {})`` default: a key
        present with no children parses as None, so `model:` alone — or
        `server:` alone — turned every read below into an AttributeError that
        killed the supervisor before llama-server was ever spawned.
        """
        return ((self.config.get("model") or {}).get("server") or {})

    def _mcp_server_cfg(self) -> dict:
        """``mcp.server`` as a dict, whatever the YAML left behind.

        ``or {}`` at BOTH levels for the same reason _llama_server_cfg does it:
        a key present with no children parses as None, so `mcp:` alone — or
        `server:` alone — turns every read below into an AttributeError that
        kills the supervisor on the branch that was about to serve MCP.
        """
        return ((self.config.get("mcp") or {}).get("server") or {})

    def _llama_port(self) -> int:
        return int(self._llama_server_cfg().get("port") or DEFAULT_LLAMA_PORT)

    def _llama_host(self) -> str:
        """The address the in-pod clients should DIAL llama-server on.

        Wildcards are mapped to loopback here, the same way _port_in_use maps
        them: `host: "::"` interpolated verbatim produced `http://:::8080`, and
        httpx.InvalidURL is not an httpx.HTTPError, so it escaped the health
        wait's guard and took PID 1 down. argv keeps the real bind address —
        llama-server must still listen on 0.0.0.0 for the :30800 NodePort.
        """
        host = self._llama_server_cfg().get("host") or "127.0.0.1"
        return "127.0.0.1" if host in ("0.0.0.0", "::", "") else str(host)

    def _llama_url(self) -> str:
        """Return the local llama-server base URL ``https://host:port``.

        https, always: llama-server is started with --ssl-cert-file /
        --ssl-key-file (client/config/parser.py) and answers nothing on plain
        HTTP, so a http:// URL here is a connection error on every in-pod
        client, not a downgrade. The node's own leaf carries IP:127.0.0.1 and
        DNS:localhost SANs precisely so this loopback dial verifies
        (orchestrator/config/tlsstore.py::node_sans).
        """
        host = self._llama_host()
        # A bare IPv6 literal ("fd00::5") needs brackets or the URL is invalid.
        if ":" in host:
            host = f"[{host}]"
        return f"https://{host}:{self._llama_port()}"

    def _llama_api_key(self) -> str:
        """model.server.api_key, or "" when auth is off.

        Read from the config rather than the environment so the per-node YAML
        pushed to /etc/aureax is authoritative — _start_llama_server keeps the
        child's LLAMA_API_KEY in lockstep with exactly this value.
        """
        return str(self._llama_server_cfg().get("api_key") or "")

    def _mcp_api_key(self) -> str:
        """mcp.server.api_key, or "" when the MCP port is unauthenticated.

        Config only. Unlike llama-server, whose key has to cross a process
        boundary through LLAMA_API_KEY, the MCP server runs in THIS process —
        so there is no MCP_API_KEY environment variable at all, on purpose. One
        would be a second source of truth for the same secret, and it would be
        readable in `kubectl exec <pod> -- env` and in /proc/<pid>/environ by
        every process on the node (the pods run hostPID).
        """
        return str(self._mcp_server_cfg().get("api_key") or "")

    def _shard_role(self) -> str:
        """`node.role` — 'shard_worker' selects rpc-server instead of llama-server."""
        return node_role(self.config)

    @staticmethod
    def _port_in_use(host: str, port: int, timeout: float = 0.3) -> bool:
        """True if something accepts a TCP connection at host:port.

        Address family comes from getaddrinfo rather than being hardcoded to
        AF_INET: this probe is what tells a shard worker its own rpc-server came
        up, and with an IPv6 bind address an AF_INET socket can never connect —
        so the worker would declare itself dead while serving perfectly.
        """
        target = "127.0.0.1" if host in ("0.0.0.0", "::", "") else host
        try:
            infos = socket.getaddrinfo(target, port, type=socket.SOCK_STREAM)
        except OSError:
            return False
        for family, socktype, proto, _canon, sockaddr in infos:
            with socket.socket(family, socktype, proto) as s:
                s.settimeout(timeout)
                try:
                    if s.connect_ex(sockaddr) == 0:
                        return True
                except OSError:
                    continue
        return False

    @staticmethod
    def _rpc_hello(host: str, port: int, timeout: float = 1.0) -> tuple[str, tuple[int, int, int] | None]:
        """Probe an rpc-server with the protocol's own HELLO.

        Returns ``("closed", None)`` when nothing accepts the connection,
        ``("silent", None)`` when something accepted it but did not answer a
        well-formed HELLO within ``timeout`` (a pre-HELLO server, a different
        service, or a reply of the wrong shape), and ``("ok", (major, minor,
        patch))`` for a real rpc-server. The connection is closed afterwards;
        the server serves one client at a time with a listen backlog of 1, so
        the probe must never linger — and it is only ever sent BEFORE this
        head's llama-server attaches, never while it is connected
        (ARCHITECTURE.md, "Invariants and how each is enforced": a worker's
        :50052 is never dialled from off-node).
        """
        target = "127.0.0.1" if host in ("0.0.0.0", "::", "") else host
        try:
            infos = socket.getaddrinfo(target, port, type=socket.SOCK_STREAM)
        except OSError:
            return "closed", None
        request = bytes([_RPC_CMD_HELLO]) + struct.pack("<Q", _RPC_CONN_CAPS_SIZE) + bytes(_RPC_CONN_CAPS_SIZE)
        for family, socktype, proto, _canon, sockaddr in infos:
            with socket.socket(family, socktype, proto) as s:
                s.settimeout(timeout)
                try:
                    s.connect(sockaddr)
                except OSError:
                    continue
                try:
                    s.sendall(request)
                    size_raw = _recv_exact(s, 8)
                    if size_raw is None:
                        return "silent", None
                    (size,) = struct.unpack("<Q", size_raw)
                    if size != _RPC_HELLO_REPLY_SIZE:
                        return "silent", None
                    reply = _recv_exact(s, size)
                    if reply is None:
                        return "silent", None
                    return "ok", (reply[0], reply[1], reply[2])
                except OSError:
                    return "silent", None
        return "closed", None

    def _llama_port_in_use(self) -> bool:
        """Probe the local port; True if something is already listening."""
        return self._port_in_use(self._llama_host(), self._llama_port())

    def _reap_stale_children(self, binary: str) -> list[int]:
        """Recover only children with a persisted Aureax ownership record."""
        from client.process_ownership import reap

        if not (self.config.get("node") or {}).get("reap_stale_children", True):
            return []
        return reap(self.node_id, binary, _REAP_WAIT_SECONDS)

    def _init_log_reporter(self) -> None:
        """Build the log shipper from the telemetry endpoint.

        The orchestrator serves /api/v1/logs alongside /api/v1/telemetry, so the
        log endpoint is derived rather than configured separately — one address
        per node, and no way for the two to drift apart.

        Deliberately independent of ``telemetry.enabled``. Shipping logs and
        sampling metrics are separate features that happen to share an address:
        a node that turns telemetry off must still ship its logs, and gating on
        it would leave exactly that node silent. Built here rather than at thread
        start so the exit paths that run before any background thread — a shard
        worker whose rpc-server dies before its port opens — still have a
        reporter to flush through.
        """
        remote_cfg = (self.config.get("telemetry") or {}).get("remote") or {}
        telemetry_endpoint = remote_cfg.get("endpoint", "")
        if self._log_store is None or not telemetry_endpoint:
            return
        endpoint = telemetry_endpoint.replace("/api/v1/telemetry", "/api/v1/logs")
        if endpoint == telemetry_endpoint:  # non-standard path; do not guess
            logger.warning(
                "Log shipping disabled — cannot derive a logs endpoint from %s",
                telemetry_endpoint,
            )
            return
        try:
            from client.log.reporter import LogReporter

            retry = remote_cfg.get("retry") or {}
            # verify inside the try, like everything else here: this runs from
            # __init__, before start()'s _require_tls_files has had a chance to
            # exit 78 with the actionable message, so a node with no CA must
            # degrade to "log shipping disabled" for the few milliseconds until
            # that check runs — not raise out of the constructor.
            self._log_reporter = LogReporter(
                store=self._log_store,
                endpoint=endpoint,
                verify=self._tls_context(),
                node_id=self.node_id,
                cursor_path=str(self._log_store.db_path) + ".cursor",
                max_attempts=retry.get("max_attempts", 3),
                backoff_base=retry.get("backoff_base_seconds", 30),
                backoff_max=retry.get("backoff_max_seconds", 300),
            )
            logger.info("Log shipping enabled -> %s", endpoint)
        except Exception as e:
            logger.warning("Log shipping disabled — %s", e)

    def _flush_crash_context(self, rc: int | None) -> None:
        """Persist the child's buffered pre-crash output, best effort."""
        capture = getattr(self, "_child_capture", None)
        if capture is None:
            return
        with contextlib.suppress(Exception):
            capture.flush_crash_context(rc if rc is not None else -1)

    def _ship_logs_now(self) -> None:
        """Push pending log entries immediately.

        Called on the way out of a dying pod: waiting for the next scheduled
        push would lose exactly the batch that explains the exit.
        """
        reporter = getattr(self, "_log_reporter", None)
        if reporter is None:
            return
        with contextlib.suppress(Exception):
            reporter.drain()

    def _exit_reporting(self, status: int, rc: int | None = None) -> None:
        """Tear down the child, flush its crash context, ship, then exit.

        Every FAILURE path goes through here. Doing it in one place is what
        keeps the "why did it die" batch from being lost by whichever exit
        happens to be taken: an exit written by hand tends to skip either the
        flush (so the crash is unexplained) or stop() (so a hostPID
        llama-server is left running for the next pod's reaper).

        NOT the SIGTERM path: _handle_signal deliberately does not flush or
        ship, because drain() can outlast the 45s terminationGracePeriod that
        daemonset-edge.yaml pins ahead of shutdown_timeout_seconds. A clean
        shutdown relies on the hostPath-persisted cursor instead, which the
        next pod start re-reads and ships from.

        stop() runs FIRST: it terminates a still-live child and joins the
        pump thread, so the child's final output lands in the capture before
        the flush below reads it.
        """
        self.stop()
        self._flush_crash_context(rc)
        self._ship_logs_now()
        sys.exit(status)

    def _init_log_store(self) -> None:
        """Open the local log buffer and mirror this process's own logging into it.

        Best-effort throughout: a node that cannot open the store must still
        serve. Losing log shipping is a visibility regression, not an outage,
        and failing here would turn it into one.
        """
        log_cfg = self.config.get("logging") or {}
        if not log_cfg.get("ship_logs", True):
            return
        try:
            from client.log.store import LogStore

            self._log_store = LogStore(log_cfg.get("log_db_path", "/opt/aureax/logs/system.db"))
        except Exception as e:
            logger.warning("Log shipping disabled — could not open log store: %s", e)
            return

        # Mirror the supervisor's own warnings/errors. Without this the store
        # would carry the child's failures but not the supervisor's own, and a
        # supervisor-side traceback — the shape a planner crash loop takes —
        # would never reach the orchestrator at all.
        #
        # Attached to "aureax", so every module logger must be named
        # "aureax.<something>" to be captured. See the logger at the top of
        # this file.
        store = self._log_store

        class _StoreHandler(logging.Handler):
            def emit(self, record: logging.LogRecord) -> None:
                # The shipper must not log into its own queue. While the
                # orchestrator is unreachable every failed push logs three
                # warnings and an error, which would be stored, shipped,
                # fail, and log again — the store fills with a record of its
                # own inability to empty. Measured after a dashboard restart:
                # the first batch to arrive was almost entirely this.
                # Telemetry's reporter is NOT excluded: "telemetry was down"
                # is real information, and it does not feed back here.
                if record.name.startswith("aureax.logship"):
                    return
                level = {
                    "WARNING": "warn",
                    "ERROR": "error",
                    "CRITICAL": "error",
                }.get(record.levelname, "info")
                with contextlib.suppress(Exception):
                    store.append(level, self.format(record), source="supervisor")

        handler = _StoreHandler()
        handler.setLevel(logging.WARNING)
        handler.setFormatter(logging.Formatter("%(name)s: %(message)s"))
        logging.getLogger("aureax").addHandler(handler)

    def _affinity_preexec(self):
        """Return a preexec hook pinning the child to ``node.cpu_affinity``.

        ``None`` when no affinity is configured, which keeps the spawn path
        byte-identical to before for every node that does not set it.

        Pinning happens in the child between fork and exec rather than via a
        ``taskset`` wrapper: a wrapper puts an extra process between the
        supervisor and its child, breaking the exit-code propagation
        ``_run_shard_worker`` relies on to let K8s see a dead rpc-server. There
        are also two runtime images on different bases
        (``docker/Dockerfile.client``, ``docker/Dockerfile.client.cuda``) and
        neither is built to guarantee a wrapper binary is present, so none can
        be assumed on every node.
        """
        cpus = (self.config.get("node") or {}).get("cpu_affinity") or []
        if not cpus:
            return None
        # Linux-only syscall; absent on macOS, where the tests run.
        if not hasattr(os, "sched_setaffinity"):
            logger.warning("node.cpu_affinity set but sched_setaffinity is unavailable")
            return None

        try:
            available = os.sched_getaffinity(0)
        except OSError:
            available = set()

        wanted = {int(c) for c in cpus}
        usable = (wanted & available) if available else wanted
        if not usable:
            # Pinning to cores this process cannot use would make the child
            # fail to exec at all, so decline rather than take the node down.
            logger.warning(
                "node.cpu_affinity %s intersects none of the available CPUs %s — not pinning",
                sorted(wanted),
                sorted(available),
            )
            return None
        if usable != wanted:
            logger.warning(
                "node.cpu_affinity %s partially unavailable; pinning to %s",
                sorted(wanted),
                sorted(usable),
            )

        logger.info("Pinning inference child to CPUs %s", sorted(usable))

        # Body kept to a single bare syscall on purpose. preexec_fn runs in the
        # forked child of a process that HAS other threads (telemetry, log-tee),
        # and any lock those threads held at fork time is permanently locked in
        # the child — so allocating, logging or importing here can deadlock
        # before exec. `usable` is built above, in the parent, for that reason.
        def _preexec() -> None:
            os.sched_setaffinity(0, usable)

        return _preexec

    def _spawn_child(self, name: str, cmd: list[str], log_path: Path) -> None:
        from client.process_ownership import spawn_guard

        with spawn_guard(self.node_id, cmd[0]):
            self._spawn_child_locked(name, cmd, log_path)

    def _spawn_child_locked(self, name: str, cmd: list[str], log_path: Path) -> None:
        """Spawn the managed inference child, teeing its output.

        The child's stdout+stderr go to BOTH ``log_path`` and this process's
        stdout. The container-stdout half is what makes failures diagnosable:
        ``kubectl logs`` and the orchestrator's crash-log fetchers only ever
        see container stdout, so a child that logs solely to a file on the
        node reduces every crash to "exited with code N". That matters most
        for distributed inference, where the useful text ("failed to connect
        to <peer>", RPC handshake mismatches, GGML asserts) is emitted by the
        child and nothing else reports it.
        """
        logger.info("Starting %s: %s", name, " ".join(cmd))
        # Before spawning, not after: an orphan from a previous incarnation is
        # still holding this group's RPC slots, and our child would otherwise
        # wait on peers it can never reach.
        survivors = self._reap_stale_children(cmd[0])
        if survivors:
            logger.error(
                "A previously managed %s is still active (pid(s) %s) — not spawning a second one",
                Path(cmd[0]).name, survivors,
            )
            # _exit_reporting rather than a raise: main() installs no handler,
            # so an exception here would end PID 1 with a traceback and skip the
            # one path that ships the crash context and the pending logs.
            self._exit_reporting(1)
        log_path.parent.mkdir(parents=True, exist_ok=True)

        preexec = self._affinity_preexec()

        # Long-lived FD written by the pump thread; closed in stop(). Opened
        # before Popen so we can release it if Popen raises (binary missing).
        log_file = _CappedLogFile(log_path)
        try:
            proc = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                preexec_fn=preexec,
            )
        except BaseException:
            log_file.close()
            raise

        from client.process_ownership import remember

        try:
            remember(self.node_id, cmd[0], proc.pid)
        except BaseException:
            proc.terminate()
            proc.wait(timeout=10)
            log_file.close()
            raise
        self._child_proc = proc
        self._child_name = name
        self._child_log_file = log_file

        # Kept so stop() can let the pump drain before closing the log FD —
        # otherwise the last lines the child wrote on its way out, which are
        # exactly the ones worth having, are lost.
        self._child_capture = self._make_child_capture(name)
        self._child_log_thread = threading.Thread(
            target=self._pump_child_output,
            args=(proc.stdout, log_file, f"[{name}] ", self._child_capture),
            daemon=True,
            name=f"{name}-log",
        )
        self._child_log_thread.start()

        logger.info("%s started (PID %d)", name, proc.pid)

    def _make_child_capture(self, name: str):
        """A ChildLogCapture for this child, or None when shipping is off."""
        # getattr, not attribute access: tests (and any caller) build this
        # object with __new__ and set only the fields they exercise.
        store = getattr(self, "_log_store", None)
        if store is None:
            return None
        from client.log.capture import ChildLogCapture

        log_cfg = self.config.get("logging") or {}
        return ChildLogCapture(
            store,
            source=name,
            ship_levels=tuple(log_cfg.get("ship_levels") or ("warn", "error")),
            context_lines=int(log_cfg.get("crash_context_lines", 80)),
        )

    @staticmethod
    def _pump_child_output(stream, log_file, prefix: str, capture=None) -> None:
        """Forward child output to the log file and container stdout, line by line.

        Also feeds `capture`, which is what makes a crash on this node visible
        from the orchestrator at all — see client/log/capture.py.
        """
        try:
            for raw in iter(stream.readline, b""):
                line = raw.decode("utf-8", errors="replace")
                with contextlib.suppress(ValueError, OSError):
                    # log FD may be closed by stop() while the child still writes
                    log_file.write(line)
                    log_file.flush()
                sys.stdout.write(prefix + line)
                sys.stdout.flush()
                if capture is not None:
                    capture.observe(line)
        except (ValueError, OSError):
            pass  # pipe closed during shutdown
        finally:
            with contextlib.suppress(ValueError, OSError):
                stream.close()

    def _start_llama_server(self) -> None:
        """Start the llama.cpp server as a child process."""
        args = get_llama_server_args(self.config)
        llama_binary = os.environ.get("LLAMA_SERVER_PATH", "llama-server")

        log_path = Path(
            (self.config.get("logging") or {}).get("llama_log_path")
            or "/opt/aureax/logs/llama-server.log"
        ).expanduser()

        # THE key handoff. Set on os.environ, not passed in argv: _spawn_child
        # passes no env= so the child inherits ours, and argv is world-readable
        # under hostPID and logged verbatim by _spawn_child into both log
        # sinks. llama-server applies LLAMA_API_KEY through the same append
        # handler as --api-key, so this is exactly equivalent to the flag.
        # Precedent: LLAMA_CACHE, set the same way in _run_shard_worker.
        #
        # Lives here rather than in _spawn_child because _spawn_child is shared
        # with rpc-server, which has no key concept at all.
        api_key = self._llama_api_key()
        if api_key:
            os.environ["LLAMA_API_KEY"] = api_key
            logger.info("llama-server API key auth ENABLED (key from model.server.api_key)")
        else:
            # POPPED, not merely skipped: the child inherits our whole
            # environment, so a LLAMA_API_KEY set by anything else (a DaemonSet
            # env block, a debug shell) would keep auth on for a node whose
            # config says it is off — while the in-pod clients, which read the
            # config, would send no header and 401 against their own server.
            os.environ.pop("LLAMA_API_KEY", None)

        self._spawn_child("llama-server", [llama_binary, *args], log_path)

    def _run_shard_worker(self) -> None:
        """Run as a shard worker: supervise rpc-server, report telemetry, block.

        No llama-server and no MCP server — this node holds a share of the
        group's weights and executes tensor ops for the head.
        """
        rpc_cfg = (self.config.get("model") or {}).get("rpc_server") or {}
        port = resolve_rpc_port(self.config)
        binary = os.environ.get("RPC_SERVER_PATH", "rpc-server")

        # rpc-server reads its tensor cache location from LLAMA_CACHE. Pointing
        # it at the hostPath-backed data dir is what stops a pod restart from
        # re-pulling this node's multi-GiB share across the network.
        # An empty cache_dir with cache enabled would still emit `-c` while
        # leaving LLAMA_CACHE unset, so rpc-server caches into its own working
        # directory inside the container — lost on every restart, silently
        # restoring the multi-GiB re-pull the cache exists to prevent. Fall back
        # to the default path rather than accepting the half-configured state.
        #
        # Expanded ONCE and reused: llama.cpp does no tilde expansion, so
        # creating $HOME/rpc-cache while exporting a literal "~/rpc-cache"
        # would make rpc-server cache into a directory named "~" under its
        # container cwd — the same lost-on-restart outcome. $HOME is inside the
        # container and outside the /opt/aureax hostPath mount, so a "~" path
        # still costs the re-pull; only an absolute path under the data dir
        # survives.
        cache_dir = str(Path(rpc_cfg.get("cache_dir") or "/opt/aureax/rpc-cache").expanduser())
        if rpc_cfg.get("cache", True):
            Path(cache_dir).mkdir(parents=True, exist_ok=True)
            os.environ["LLAMA_CACHE"] = cache_dir

        # Same logging.llama_log_path key as the head: it names whichever child
        # this node manages, and the worker templates point it at
        # rpc-server.log. LoggingConfig's own default (schema.py, llama-server
        # .log) is validation-only — the client reads the raw dict and
        # generation ships the template's keys verbatim, so no schema default
        # ever reaches a node and this fallback is the operative one.
        log_path = Path(
            (self.config.get("logging") or {}).get("llama_log_path")
            or "/opt/aureax/logs/rpc-server.log"
        ).expanduser()

        # Before the listen wait, not after: that wait can exit the process, and
        # a worker whose rpc-server dies during load is exactly the case the
        # shipper exists for.
        self._start_log_shipping()

        # After the shipper and before rpc-server opens the cache: the audit's
        # warnings are the only record of what it deleted, and a cache that
        # rpc-server is already serving from must not be edited underneath it.
        if rpc_cfg.get("cache", True):
            self._audit_rpc_cache(cache_dir, float(rpc_cfg.get("min_free_disk_gib") or 0))

        self._spawn_child("rpc-server", [binary, *get_rpc_server_args(self.config)], log_path)
        # Probe the address rpc-server actually bound, not loopback: with
        # host "auto" it binds this node's LAN IP only, so a 127.0.0.1 check
        # never succeeds even while the server is happily serving.
        self._wait_for_rpc_listening(resolve_rpc_host(self.config), port)

        self._start_telemetry()

        # Block until rpc-server exits, then propagate its code so K8s restarts
        # the pod rather than leaving a live container with no worker in it.
        #
        # POLLED, not Popen.wait(). This is the main thread, so _handle_signal
        # runs *inside* whatever call is parked here — and a blocking wait() holds
        # CPython's non-reentrant _waitpid_lock across os.waitpid, which makes the
        # handler's own stop() see poll() as None (the lock is unavailable) and
        # spin the full shutdown_timeout_seconds before logging a SIGKILL for an
        # already-dead child. Every worker teardown then looks like a 30s hang.
        # The 1s granularity matches _wait_for_rpc_listening and costs nothing on
        # a process that lives for hours.
        while not self._shutdown and self._child_proc.poll() is None:
            time.sleep(1)
        rc = self._child_proc.returncode
        if not self._shutdown:
            logger.error(
                "rpc-server exited with code %d — see the [rpc-server] lines above", rc
            )
            # A worker has no HTTP server and no reachable kubelet, so this is
            # the ONLY way the run-up to its death reaches the orchestrator.
            self._exit_reporting(_exit_status(rc), rc)
        sys.exit(_exit_status(rc))

    def _audit_rpc_cache(self, cache_dir: str, min_free_gib: float) -> None:
        """Check the worker's tensor cache before rpc-server opens it.

        rpc-server's cache (``<cache_dir>/rpc/<fnv1a64>``) is content-addressed
        and written in place: a file is named by the hash of the bytes it
        holds, nothing ever deletes one, and on a hit the server trusts the
        file's size without re-hashing. Two things follow, both read from
        ggml-rpc.cpp at b10375 rather than observed here:

        - A pod killed mid-write leaves a TRUNCATED weight that the next load
          accepts silently, as a partial tensor. The manifest's byte size is
          what catches it. (Not re-checked at the current pin, b11429.)
        - At b10375 every tensor over 10 MiB that the head sent was cached,
          not only weights: a prefill attention mask passes that threshold
          once the prompt is ~10k tokens deep, so one long prompt wrote
          gigabytes of mask files that were never read back and never
          removed. Upstream restricted the cache to weights in b10985, so the
          pinned build (b11429) no longer writes them; this half of the audit
          is now the backstop that clears what an older image left behind.

        With a manifest that carries hashes, every file is classified by name
        and size; with a sizes-only manifest, by size; without one, nothing is
        deleted and the audit only reports. Dotfiles are the seeder's partial
        exports and are always removed. Then the free-space floor: a full
        hostPath takes the kubelet down with it, so a worker below the floor
        does not start.
        """
        cache_root = Path(cache_dir)
        if not cache_root.is_dir():
            logger.debug("rpc-cache audit skipped: %s does not exist", cache_dir)
            return
        rpc_dir = cache_root / "rpc"

        manifest = self._load_rpc_cache_manifest()
        entries = (manifest or {}).get("entries") or []
        by_hash: dict[str, int] = {}
        sizes: set[int] = set()
        for entry in entries:
            try:
                nbytes = int(entry["nbytes"])
            except (KeyError, TypeError, ValueError):
                continue
            sizes.add(nbytes)
            if entry.get("hash"):
                by_hash[str(entry["hash"])] = nbytes

        kept = kept_bytes = 0
        removed: dict[str, list[str]] = {"unknown": [], "mismatched": [], "partial": []}
        if rpc_dir.is_dir():
            for path in sorted(rpc_dir.iterdir()):
                if not path.is_file():
                    continue
                size = path.stat().st_size
                if path.name.startswith("."):
                    verdict = "partial"
                elif manifest is None:
                    verdict = "keep"
                elif path.name in by_hash:
                    verdict = "keep" if size == by_hash[path.name] else "mismatched"
                elif by_hash:
                    verdict = "unknown"
                else:
                    verdict = "keep" if size in sizes else "unknown"

                if verdict == "keep":
                    kept += 1
                    kept_bytes += size
                    continue
                try:
                    path.unlink()
                    removed[verdict].append(f"{path.name} ({size} B)")
                except OSError as e:
                    logger.warning("rpc-cache audit: could not remove %s: %s", path, e)

        source = "no manifest, report only" if manifest is None else (
            f"manifest with {len(by_hash)} hashed of {len(entries)} entries"
            if by_hash else f"sizes-only manifest, {len(entries)} entries"
        )
        logger.info(
            "rpc-cache audit: kept %d file(s), %.2f GiB in %s (%s)",
            kept, kept_bytes / 2**30, rpc_dir, source,
        )
        for kind, names in removed.items():
            if names:
                logger.warning(
                    "rpc-cache audit: removed %d %s file(s) from %s: %s",
                    len(names), kind, rpc_dir, ", ".join(names[:8]) + (" ..." if len(names) > 8 else ""),
                )

        if min_free_gib > 0:
            free = shutil.disk_usage(cache_root).free
            if free < min_free_gib * 2**30:
                logger.error(
                    "refusing to start rpc-server: %.2f GiB free on %s, below "
                    "model.rpc_server.min_free_disk_gib = %.1f. A full cache filesystem "
                    "takes the node down; free space there (the audit above removed what "
                    "it could identify) or lower the floor in this node's config.",
                    free / 2**30, cache_dir, min_free_gib,
                )
                self._exit_reporting(1)

    def _load_rpc_cache_manifest(self) -> dict | None:
        """The deployer-installed manifest, or None when absent or unreadable.

        Unreadable is treated like absent, loudly: a manifest that cannot be
        parsed must not turn into "delete everything" or "delete nothing"
        silently — it becomes report-only with a warning naming the file.
        """
        path = Path(_RPC_CACHE_MANIFEST)
        if not path.is_file():
            return None
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            logger.warning("rpc-cache manifest %s is unreadable (%s); auditing report-only", path, e)
            return None
        if not isinstance(data, dict) or not isinstance(data.get("entries"), list):
            logger.warning("rpc-cache manifest %s has no entries list; auditing report-only", path)
            return None
        return data

    def _block_on_child(self) -> None:
        """Supervise the inference child until it exits, then propagate its code.

        Same polled loop as _run_shard_worker, for the same signal-handling
        reason documented there. With no child of our own (the attach branch),
        idle until a signal arrives — exiting would take down a pod fronting a
        llama-server that is serving fine.
        """
        while not self._shutdown and (
            getattr(self, "_child_proc", None) is None or self._child_proc.poll() is None
        ):
            time.sleep(1)
        if getattr(self, "_child_proc", None) is None or self._shutdown:
            return
        rc = self._child_proc.returncode
        logger.error(
            "llama-server exited with code %s — see the [llama-server] lines above", rc
        )
        self._exit_reporting(_exit_status(rc) or 1, rc)

    def _wait_for_rpc_listening(
        self, host: str, port: int, timeout: int = _RPC_LISTEN_TIMEOUT
    ) -> None:
        """Wait for our own rpc-server to accept connections on `host:port`."""
        start = time.time()
        while time.time() - start < timeout:
            if self._shutdown:
                return
            if self._port_in_use(host, port):
                logger.info(
                    "rpc-server listening on %s:%d after %.1fs", host, port, time.time() - start
                )
                return
            if self._child_proc and self._child_proc.poll() is not None:
                rc = self._child_proc.returncode
                logger.error("rpc-server exited with code %d before listening", rc)
                # _exit_status, not a literal 1: a signal death must surface as
                # 137/143 rather than the exit code of a config error. `or 1`
                # because a child exiting 0 mid-load is still a failure here.
                self._exit_reporting(_exit_status(rc) or 1, rc)
            time.sleep(1)

        logger.error("rpc-server did not listen on %s:%d within %ds", host, port, timeout)
        self._exit_reporting(1)

    def _wait_for_rpc_workers(self) -> None:
        """Block until every configured RPC peer accepts connections.

        llama-server exits immediately if a peer is unreachable at load time,
        so without this the head crash-loops until K8s backoff happens to line
        up with the workers being ready. Doing it here rather than in the
        orchestrator means the ordering also holds for pod restarts, node
        reboots and `kubectl rollout restart` — not just first deploy.
        """
        server_cfg = self._llama_server_cfg()
        peers = [str(p) for p in (server_cfg.get("rpc_servers") or [])]
        if not peers:
            return

        # Validate the peer list before spending the timeout on it. An entry
        # that isn't host:port can never become reachable, so treating it like a
        # slow node buys nothing but a confusing five-minute wait — which is
        # exactly what an unresolved "${rpc_servers}" placeholder produces.
        malformed = [p for p in peers if not _is_host_port(p)]
        if malformed:
            logger.error(
                "Malformed RPC peer(s) in model.server.rpc_servers: %s — expected host:port",
                ", ".join(repr(p) for p in malformed),
            )
            self._exit_reporting(1)

        timeout = int(
            (self.config.get("node") or {}).get("worker_wait_timeout_seconds") or 300
        )
        logger.info("Waiting for %d RPC worker(s): %s", len(peers), ", ".join(peers))

        start = time.time()
        # Parsed once — the malformed gate above already proved every entry
        # splits into a usable host:port.
        pending: list[tuple[str, str, str]] = []
        for p in peers:
            host, _, port_s = p.rpartition(":")
            pending.append((p, host, port_s))
        expected = _expected_rpc_proto()
        silent_warned: set[str] = set()
        last_progress = 0.0
        while pending and time.time() - start < timeout:
            if self._shutdown:
                return
            still: list[tuple[str, str, str]] = []
            for peer, host, port_s in pending:
                state, version = self._rpc_hello(host, int(port_s), timeout=1.0)
                if state == "ok":
                    major, minor, patch = version
                    if expected is not None and (major, minor) != expected:
                        # Fail NOW, by name. Left alone, llama-server would
                        # connect, reject the handshake and exit — or, against
                        # a pre-HELLO server, hang in it — and the only
                        # record would be the startupProbe giving up later.
                        logger.error(
                            "RPC worker %s speaks RPC protocol %d.%d.%d but this image expects "
                            "%d.%d — the group is running two llama.cpp builds. Rebuild the "
                            "odd one out with ./scripts/build-on-node.sh <host> (or the whole "
                            "fleet with ./scripts/update-all.sh), then `aureax stop && aureax "
                            "start`: apply never restarts workers.",
                            peer, major, minor, patch, expected[0], expected[1],
                        )
                        self._exit_reporting(1)
                    logger.info("  worker %s is up (RPC protocol %d.%d.%d)", peer, major, minor, patch)
                    continue
                if state == "silent" and peer not in silent_warned:
                    silent_warned.add(peer)
                    logger.warning(
                        "  worker %s accepts TCP but did not answer the RPC HELLO within 1s — "
                        "an rpc-server from a build that predates HELLO, something else on the "
                        "port, or a server still coming up; waiting",
                        peer,
                    )
                still.append((peer, host, port_s))
            pending = still
            if not pending:
                break

            elapsed = time.time() - start
            if elapsed - last_progress >= 15:
                last_progress = elapsed
                logger.info(
                    "  still waiting on %s (%.0fs / %ds)",
                    ", ".join(p for p, _, _ in pending), elapsed, timeout,
                )
            time.sleep(2)

        if pending:
            # Name the unreachable peers: with several workers, "it hung" is
            # otherwise indistinguishable from "one box is off".
            logger.error(
                "RPC worker(s) unreachable after %ds: %s — not starting llama-server",
                timeout, ", ".join(p for p, _, _ in pending),
            )
            self._exit_reporting(1)

        logger.info("All %d RPC worker(s) reachable after %.1fs", len(peers), time.time() - start)

    def _llama_health_timeout(self) -> int:
        """Seconds to wait for llama-server to become healthy.

        Configurable because load time is dominated by model size and, for a
        sharded group, by shipping every tensor to the RPC peers over the
        network. A 27B model split across a 1 GbE fabric takes minutes, not
        the seconds a small local model takes.
        """
        return int(
            self._llama_server_cfg().get("health_timeout_seconds") or DEFAULT_HEALTH_TIMEOUT_SECONDS
        )

    def _wait_for_llama_health(self, timeout: int | None = None) -> None:
        """Wait for llama-server to respond to health checks."""
        if timeout is None:
            timeout = self._llama_health_timeout()
        url = f"{self._llama_url()}/health"
        attached = getattr(self, "_child_proc", None) is None

        # /health is auth-exempt on the pinned build (b11429), so the header is
        # belt-and-braces: upstream removing an exemption is a known upgrade
        # landmine (see ARCHITECTURE.md, "llama-server API-key
        # authentication"), and a build that gates /health would otherwise make
        # every keyed head crash-loop with "model load timed out".
        key = self._llama_api_key()
        headers = {"Authorization": f"Bearer {key}"} if key else None

        logger.info("Waiting for llama-server at %s (timeout %ds) ...", url, timeout)
        start = time.time()
        last_progress = 0.0
        warned_401 = False

        # One client for the whole wait, and one shared SSL context behind it:
        # httpx.Client() builds a context (a CA-bundle load) per construction,
        # and at one probe every 2s across a ~280s cold sharded load that is
        # ~140 of them on a node already saturated by the model load.
        with httpx.Client(timeout=5, verify=self._tls_context()) as client:
            while time.time() - start < timeout:
                if self._shutdown:
                    return
                try:
                    resp = client.get(url, headers=headers)
                    if resp.status_code == 200:
                        logger.info("llama-server healthy after %.1fs", time.time() - start)
                        return
                    if resp.status_code == 401 and not warned_401:
                        # Still a failure — on today's build /health is exempt,
                        # so a 401 means the key is wrong, not that auth moved.
                        warned_401 = True
                        logger.error(
                            "llama-server answered 401 on %s — model.server.api_key does not "
                            "match the running server", url,
                        )
                except httpx.HTTPError:
                    # The whole family, not just ConnectError/TimeoutException: a
                    # server that accepts the socket mid-load and then closes it
                    # raises ReadError or RemoteProtocolError, and letting those
                    # escape kills the supervisor during a perfectly normal load.
                    # A pooled keep-alive dropped by a mid-load server lands here
                    # too, costing one extra interval.
                    pass

                # Check if llama-server crashed
                if self._child_proc and self._child_proc.poll() is not None:
                    rc = self._child_proc.returncode
                    logger.error(
                        "llama-server exited with code %d — see the [llama-server] lines above",
                        rc,
                    )
                    # _exit_status, not a literal 1: an OOM-killed load is the
                    # failure the shard workers' memory limit is tuned to
                    # produce, and K8s must show 137, not "Error, exit code 1".
                    # `or 1` because a child exiting 0 mid-load is still fatal.
                    self._exit_reporting(_exit_status(rc) or 1, rc)

                # Heartbeat so a long model load is visibly progress, not a hang.
                elapsed = time.time() - start
                if elapsed - last_progress >= 30:
                    last_progress = elapsed
                    logger.info("  still loading (%.0fs / %ds)", elapsed, timeout)

                # Literal, like _wait_for_rpc_workers' own 2s: no caller ever
                # supplied an interval, and configs/aureax-shard-head-35b.yaml
                # documents this poll as "every 2 s".
                time.sleep(2)

        if attached:
            logger.error(
                "Attached llama-server never became healthy within %ds — the process holding "
                "this port is not a working server", timeout,
            )
        else:
            logger.error("llama-server failed to become healthy within %ds", timeout)
        self._exit_reporting(1)

    def _refuse_unauthenticated_attach(self) -> None:
        """On the attach branch: refuse a server that enforces no API key.

        The process holding the port was not started by this supervisor and is
        not a recorded child, so the reaper never touches it and its auth state
        is whatever it was launched with. A leftover or foreign llama-server
        started with no key answers /health, the pod goes Ready, and this node
        then serves inference through :30800 with no bearer gate while its
        config says auth is on — under hostNetwork, on the node's public
        inference port. Crash-looping the pod is the lesser outcome, and it is
        the state an operator can see.

        Only when this node's config carries a key: a fleet running with auth
        off has nothing to enforce. The probe is /props, deliberately WITHOUT an
        Authorization header — /health is auth-exempt, so it proves nothing,
        while /props is gated on the pinned build (see ARCHITECTURE.md,
        "llama-server API-key authentication"). Only a 2xx acts: a 401, any
        other status and a transport error all leave the attach alone, because
        this check fires on positive evidence that the port is open, never on
        the absence of evidence.
        """
        if not self._llama_api_key():
            return
        url = f"{self._llama_url()}/props"
        try:
            with httpx.Client(timeout=5, verify=self._tls_context()) as client:
                resp = client.get(url)
        except httpx.HTTPError as e:
            logger.warning(
                "Could not verify the attached llama-server's API-key auth (%s) — continuing", e
            )
            return
        if 200 <= resp.status_code < 300:
            logger.error(
                "Attached llama-server answered %d to an UNAUTHENTICATED %s while "
                "model.server.api_key is set — the process holding port %d enforces no key, "
                "so this node would serve inference ungated. Refusing to front it.",
                resp.status_code, url, self._llama_port(),
            )
            self._exit_reporting(1)

    def _verify_rpc_topology(self) -> None:
        """After /health: refuse a peer list this node's own split cannot address.

        A head whose --rpc list and --tensor-split disagree still loads,
        answers /health and serves. Nothing else in the stack can see it: the
        pod is Ready, the group's MCP endpoint answers, `aureax status` reports
        the group up, and test-all.sh's rpc-server checks only run against the
        workers it was told about. llama.cpp resolves RPC0..RPCn positionally
        from --rpc order, so a split of the wrong length either drops a peer's
        share on the floor or addresses a device that does not exist.

        validate_groups (orchestrator/config/templating.py) already checks this
        at generate time, so this catches only what generate cannot see: the
        file this node ACTUALLY has. A hand-edited or half-written
        /etc/aureax/aureax-edge.yaml is exactly that case.

        Only the structural check runs here. At b10375 (verified live; not
        re-checked at the current pin, b11429) /props carries no device list
        and no flash-attention field, and
        llama-server.log at the default verbosity prints neither — so a runtime
        device-count or flash-attention check would have nothing to read, and a
        guessed JSON key or log pattern would be inert while looking enforced.
        The flash-attention invariant is enforced instead by the worker memory
        limit in k8s/daemonset-shard.yaml, which sits between the FA-on and
        FA-off peaks.
        """
        server_cfg = self._llama_server_cfg()
        peers = [str(p) for p in (server_cfg.get("rpc_servers") or [])]
        if not peers:
            # Not a sharded head: --tensor-split is never emitted without
            # --rpc (client/config/parser.py), so there is nothing to compare.
            return
        split = list(server_cfg.get("tensor_split") or [])
        # One RPC device per peer unless the generator stamped the real count
        # (a worker exposing two GPUs is two devices behind one address).
        expected = int(server_cfg.get("rpc_device_count") or len(peers))
        if not split or len(split) == expected:
            # An empty split is llama.cpp's own free-memory split, which is a
            # documented configuration, not a mismatch.
            return

        logger.error(
            "model.server.tensor_split has %d entries but the group's %d peer(s) expose "
            "%d RPC device(s) — this node's /etc/aureax/aureax-edge.yaml does not match what "
            "`aureax generate` produces. Re-run `aureax apply --node %s`.",
            len(split), len(peers), expected, self.node_id,
        )
        self._exit_reporting(1)

    def _start_telemetry(self) -> None:
        """Start background telemetry collection and push loop."""
        telemetry_cfg = self.config.get("telemetry") or {}
        # Absent means yes, matching schema.py::TelemetryConfig.enabled. A
        # default of False here would let a template that omits the key
        # validate as telemetry-on while the node ships nothing — and
        # /api/nodes is derived entirely from the telemetry database, so the
        # node would simply never appear.
        if not telemetry_cfg.get("enabled", True):
            logger.info("Telemetry disabled, skipping")
            return

        local_cfg = telemetry_cfg.get("local") or {}
        remote_cfg = telemetry_cfg.get("remote") or {}

        db_path = local_cfg.get("db_path") or "/opt/aureax/metrics/telemetry.db"
        # int() at the read site, like _start_log_shipping: these values reach
        # range() below, where a float is a TypeError at the top of a daemon
        # thread — i.e. telemetry ends silently for the life of the pod.
        sample_interval = int(local_cfg.get("sample_interval_seconds") or 60)
        push_interval = int(remote_cfg.get("push_interval_seconds") or 60)
        retention_days = int(local_cfg.get("retention_days") or 7)

        endpoint = remote_cfg.get("endpoint", "")
        retry_cfg = remote_cfg.get("retry") or {}
        # Guarded like _init_log_store, and for the same reason: the constructor
        # mkdirs and CREATE TABLEs on the hostPath-backed data dir, so a corrupt
        # telemetry.db, a full disk or a root-owned directory raised straight
        # out of start() — killing PID 1 before llama-server was even spawned,
        # identically on every restart. This call site also serves the shard
        # worker (_run_shard_worker), where the raise would abort a whole group
        # over a worker whose rpc-server was already serving.
        try:
            self.telemetry_storage = TelemetryStorage(db_path)
            reporter = TelemetryReporter(
                storage=self.telemetry_storage,
                endpoint=endpoint,
                verify=self._tls_context(),
                batch_size=remote_cfg.get("batch_size", 50),
                max_attempts=retry_cfg.get("max_attempts", 3),
                backoff_base=retry_cfg.get("backoff_base_seconds", 30),
                backoff_max=retry_cfg.get("backoff_max_seconds", 300),
            )
        except Exception as e:
            # Module logger, so _init_log_store's handler still ships it.
            logger.warning("Telemetry disabled — could not open %s: %s", db_path, e)
            return

        # A shard worker has no llama-server to poll; passing None skips the
        # inference sample rather than attempting a doomed HTTP call every
        # interval. System metrics still flow, so workers stay visible.
        llama_url = None if self._shard_role() == SHARD_WORKER_ROLE else self._llama_url()

        self._telemetry_thread = threading.Thread(
            target=self._telemetry_loop,
            # Snapshotted at thread start rather than re-read per sample: the
            # loop's only client state is node_id/telemetry_storage/_shutdown,
            # which is all the supervisor tests set on their __new__-built
            # client — self.config is never there to read.
            args=(llama_url, sample_interval, push_interval, endpoint, reporter,
                  retention_days, self._llama_api_key() or None, self._tls_context()),
            daemon=True,
            name="telemetry",
        )
        self._telemetry_thread.start()
        logger.info(
            "Telemetry started (collect every %ds, push every %ds to %s)",
            sample_interval, push_interval, endpoint or "(disabled)",
        )

    def _start_log_shipping(self) -> None:
        """Start the background log push/prune loop.

        Its own thread rather than a passenger on the telemetry loop: the two
        are separately configurable, and a node with telemetry off still needs
        its crashes to be visible from the orchestrator.

        Gated on the STORE, not the reporter: pruning is the loop's other job
        and this loop is what enforces the node's CONFIGURED retention
        (``logging.retention_days``, 7 by default). Gating on the reporter left
        a node with no derivable logs endpoint — a config whose
        telemetry.remote is unset — buffering into a hostPath-backed SQLite
        file that only LogStore's own 30-day write-time backstop ever touched.
        The push is skipped inside the loop instead.
        """
        if self._log_store is None:
            return
        log_cfg = self.config.get("logging") or {}
        remote_cfg = (self.config.get("telemetry") or {}).get("remote") or {}
        push_interval = int(remote_cfg.get("push_interval_seconds", 60))
        retention_days = int(log_cfg.get("retention_days", 7))

        self._log_thread = threading.Thread(
            target=self._log_loop,
            args=(push_interval, retention_days),
            daemon=True,
            name="logship",
        )
        self._log_thread.start()
        if self._log_reporter is None:
            logger.info("Log buffer pruning started (no logs endpoint; nothing is shipped)")
        else:
            logger.info("Log shipping started (push every %ds)", push_interval)

    def _log_loop(self, push_interval: int, retention_days: int) -> None:
        """Push pending log entries, and prune the local buffer hourly.

        This is where the node's configured retention is applied. LogStore
        self-prunes on writes too, but only against its own 30-day backstop
        (``client/log/store.py::LOG_RETENTION_DAYS``), so without this loop a
        hostPath-backed buffer keeps four weeks of a node's logs instead of
        the one its config asked for. That is why the loop runs whenever the
        store is open and only the push is skipped when there is no reporter to
        push through. The two pruners do not fight: a DELETE of rows the other
        already removed is a no-op, and each is hourly.
        """
        last_prune = 0.0
        prune_interval = 3600.0
        while not self._shutdown:
            for _ in range(max(1, push_interval)):
                if self._shutdown:
                    return
                time.sleep(1)

            # A push failure is already logged by the reporter; suppressing here
            # keeps one bad batch from ending shipping for the pod's life.
            #
            # max_batches=10, attempts=1 for the reasons _telemetry_loop states
            # at its own push below: the rows are already durable on disk, so
            # in-loop backoff blocks this thread for ~3 minutes per cycle (and
            # holds up the hourly prune that shares it) while buying nothing,
            # and one batch per push drains a backlog so slowly that the newest
            # entries — a crash context among them — stay on the node for hours.
            # The loop stops early on an empty store or a failed send, so a
            # healthy node still sends exactly one batch.
            if self._log_reporter is not None:
                with contextlib.suppress(Exception):
                    self._log_reporter.push(max_batches=10, attempts=1)

            now = time.time()
            if retention_days > 0 and (now - last_prune >= prune_interval):
                last_prune = now
                try:
                    deleted = self._log_store.prune_older_than(retention_days)
                    if deleted:
                        # "configured", against LogStore._maybe_prune's
                        # "backstop": two hourly pruners write to the same
                        # shipped log, and a line that named neither left an
                        # operator unable to tell which retention was applied.
                        logger.info("Logs: configured prune removed %d row(s) older than %dd",
                                    deleted, retention_days)
                except Exception as e:  # pruning must never kill the loop
                    logger.warning("Configured log prune failed: %s", e)

    def _telemetry_loop(
        self,
        llama_url: str | None,
        sample_interval: int,
        push_interval: int,
        endpoint: str,
        reporter: TelemetryReporter,
        retention_days: int = 7,
        api_key: str | None = None,
        verify: ssl.SSLContext | None = None,
    ) -> None:
        """Collect metrics every ``sample_interval`` seconds, push every ``push_interval``.

        Also prunes the local buffer hourly. Nothing else calls
        ``TelemetryStorage.rotate``, so without this the edge DB grows for the
        lifetime of the node and ``telemetry.local.retention_days`` is a setting
        that does nothing.
        """
        last_push = 0.0
        last_rotate = 0.0
        rotate_interval = 3600.0
        while not self._shutdown:
            # Guarded: this is the top of a daemon thread with nothing above it,
            # so an escaping exception ends telemetry for the life of the pod,
            # silently. A full disk or a lock contest raises
            # sqlite3.OperationalError here, and losing a sample is a far better
            # outcome than losing the loop.
            try:
                metrics = collect_all(self.node_id, llama_url, api_key=api_key, verify=verify)
                if metrics:
                    self.telemetry_storage.insert(metrics)
            except Exception as e:
                logger.warning("Telemetry sample failed: %s", e)

            now = time.time()
            if endpoint and (now - last_push >= push_interval):
                with contextlib.suppress(Exception):
                    # attempts=1: the rows are already durably buffered, so the
                    # reporter's own backoff (3 x 30s plus a 30s httpx timeout
                    # each) would buy no durability and would block SAMPLING
                    # for ~3 minutes per cycle — punching holes in the local
                    # buffer during exactly the outage it exists to cover. The
                    # next tick is the retry.
                    #
                    # max_batches=10: one batch per push drains a backlog at
                    # (batch_size - production rate) rows per interval, so
                    # collect_all's ~15 rows/min against a 50-row batch turns a
                    # day offline into hours of catch-up with the dashboard
                    # showing stale values throughout. The loop stops early on
                    # an empty buffer or a failed send, so a healthy node still
                    # sends exactly one.
                    reporter.push(max_batches=10, attempts=1)
                last_push = now

            if retention_days > 0 and (now - last_rotate >= rotate_interval):
                last_rotate = now
                try:
                    deleted = self.telemetry_storage.rotate(retention_days)
                    if deleted:
                        logger.info("Telemetry: pruned %d row(s) older than %dd",
                                    deleted, retention_days)
                except Exception as e:  # pruning must never kill the loop
                    logger.warning("Telemetry rotate failed: %s", e)

            # max(1, ...) like _log_loop: without the floor,
            # sample_interval_seconds: 0 is a busy loop — several /proc reads,
            # an HTTP GET of llama's /metrics and a sqlite insert, flat out, on
            # a pod that carries no CPU limit.
            for _ in range(max(1, sample_interval)):
                if self._shutdown:
                    break
                time.sleep(1)

    def _start_planner(self) -> None:
        """Run the cognitive-planner MCP host (blocking).

        Connects outbound to each server in mcp.client.remote_servers and
        keeps those sessions alive while llama-server runs. Per ARCHITECTURE.md
        section 5, "Process Management Architecture", the planner pod's client
        owns the MCP host runtime; the dashboard's chat_service is a separate
        quick-test path and not the production planner.

        Idles until SIGTERM (handled by _handle_signal -> stop -> sys.exit)
        or until llama-server exits unexpectedly. Failed connects are
        retried with exponential backoff so a cold start where the edges
        aren't yet reachable does not crash the pod.
        """
        remote_servers = (
            ((self.config.get("mcp") or {}).get("client") or {}).get("remote_servers") or []
        )
        # BOTH keys, and unique names: _run_planner_host indexes s["name"] to
        # build its pending map, so an entry without one is a KeyError out of
        # asyncio.run — a crash-looping planner pod — and two entries sharing a
        # name collapse into one, leaving a peer permanently unconnected while
        # the ready count still claims it. Generated configs cannot produce
        # either shape (${mcp_endpoints} keys off the node id); a hand-edited
        # /etc/aureax/aureax-edge.yaml can.
        valid: list[dict] = []
        seen: set[str] = set()
        for s in remote_servers:
            name, url = s.get("name"), s.get("url")
            if not name or not url:
                logger.warning(
                    "MCP host: skipping %s (an entry needs both name and url)",
                    name or url or "unknown",
                )
            elif name in seen:
                logger.warning("MCP host: skipping duplicate remote server name %r", name)
            else:
                seen.add(name)
                valid.append(s)

        asyncio.run(self._run_planner_host(valid))

    async def _run_planner_host(self, valid: list[dict]) -> None:
        """MCP host event loop: connect to each remote, retry pending, watch llama."""
        from client.mcp.pool import MCPPool

        pool = MCPPool(verify=self._tls_context())
        pending = {s["name"]: (s["url"], _peer_api_key(s)) for s in valid}
        # The map, not the list it came from: a duplicated name is one entry
        # here and two there, and counting the list would report a peer as
        # expected that nothing will ever connect to.
        total = len(pending)

        async def try_connect(name: str, url: str, api_key: str | None) -> bool:
            ok = await pool.connect_url(name, url, api_key)
            # url only, never the key: this line is teed to container stdout
            # and shipped to the orchestrator's log store.
            logger.info("MCP host: %s -> %s [%s]",
                        name, url, "OK" if ok else "FAILED")
            return ok

        async def connect_pass() -> None:
            # Concurrent: connect_url soft-fails after its 5s connect timeout
            # (client/mcp/pool.py), and an unready MCP pod DROPs the SYN rather
            # than refusing it, so every cold node costs that full budget. A
            # serial pass over a fleet with several of them stalls this loop —
            # and the llama-crash watch below it — for as many multiples.
            names = list(pending)
            results = await asyncio.gather(
                *(try_connect(n, *pending[n]) for n in names),
                return_exceptions=True,
            )
            for name, ok in zip(names, results, strict=True):
                if ok is True:
                    pending.pop(name, None)

        try:
            # Initial connect pass — usually races edge MCP startup.
            await connect_pass()

            logger.info("MCP host ready: %d/%d remote servers connected",
                        len(pool.connected_nodes), total)

            # Idle: detect llama-server crash, retry pending connects
            # with exponential backoff (cap 60s).
            next_retry_at = time.monotonic() + 2.0
            backoff = 2.0
            while not self._shutdown:
                try:
                    if self._child_proc is not None and self._child_proc.poll() is not None:
                        rc = self._child_proc.returncode
                        logger.error("llama-server exited unexpectedly (rc=%s)", rc)
                        # _exit_status: a signal death must surface as 137/143,
                        # not the 247 that sys.exit(-9) wraps to.
                        self._exit_reporting(_exit_status(rc) or 1, rc)

                    if pending and time.monotonic() >= next_retry_at:
                        logger.info(
                            "MCP host: retrying %d pending server(s) in backoff", len(pending)
                        )
                        await connect_pass()
                        if pending:
                            backoff = min(backoff * 2, 60.0)
                            next_retry_at = time.monotonic() + backoff
                        else:
                            logger.info("MCP host: all remote servers connected")

                    await asyncio.sleep(1)

                except asyncio.CancelledError:
                    # A REMOTE DIED — not a shutdown. connect_url enters the MCP
                    # SDK's streamable_http_client in THIS task rather than a
                    # child, so when a server goes away the SDK's internal anyio
                    # cancel scope fires and the CancelledError surfaces here, at
                    # whatever we happen to be awaiting.
                    #
                    # Letting it propagate would exit(1) and CrashLoopBackOff
                    # the planner every time an edge node restarted: one remote
                    # blinking taking down the pod that is supposed to be
                    # orchestrating the fleet.
                    if self._shutdown:
                        raise  # genuine teardown — stop() is unwinding us

                    # Clear the cancellation the scope charged to this task, or
                    # the next await re-raises immediately and we spin.
                    current = asyncio.current_task()
                    if current is not None:
                        current.uncancel()

                    logger.warning(
                        "MCP host: a remote session was cancelled (server likely "
                        "restarted) — rebuilding the pool and reconnecting all %d",
                        total,
                    )

                    # Every session in the pool shared the torn-down scope, so
                    # they are all unusable now. Rebuild rather than reuse.
                    with contextlib.suppress(BaseException):
                        await pool.close()
                    pool = MCPPool(verify=self._tls_context())
                    pending = {s["name"]: (s["url"], _peer_api_key(s)) for s in valid}
                    backoff = 2.0
                    next_retry_at = time.monotonic() + backoff
        finally:
            with contextlib.suppress(BaseException):
                await pool.close()

    def _start_mcp_server(self) -> None:
        """Initialize and run the MCP server (blocking, in-process).

        Host/port are passed to init() which sets them on the FastMCP
        settings object; the uvicorn server below is built by hand rather than
        via ``mcp.run()`` — see the shutdown note there.
        """
        import uvicorn

        from client.mcp.server import build_app, init, mcp

        mcp_cfg = self._mcp_server_cfg()
        port = int(mcp_cfg.get("port") or 9000)

        # init() takes the MCP PORT from config; the host is the literal
        # 0.0.0.0 below because the pod runs hostNetwork and must accept the
        # NodePort Service's traffic on the node IP (there is no
        # mcp.server.host field to change it). That makes :9000 a second door
        # beside :30900 — see the "SECURITY — READ BEFORE DEPLOYING" block in
        # k8s/daemonset-edge.yaml.
        init(
            self.node_id,
            self._llama_url(),
            mcp_host="0.0.0.0",
            mcp_port=port,
            telemetry_storage=self.telemetry_storage,
            llama_api_key=self._llama_api_key() or None,
            # Config only — see _mcp_api_key. It never reaches argv or the
            # child's environment, because the server it protects runs here.
            mcp_api_key=self._mcp_api_key() or None,
            verify=self._tls_context(),
        )

        # Nothing else polls the child on this branch: _run_shard_worker and
        # _block_on_child both supervise theirs, but uvicorn below blocks
        # forever. Without this watcher a llama-server that OOMs after startup
        # goes unnoticed until the kubelet's liveness probe (3 x 30s), with the
        # crash context discarded and the child never reaped.
        self._watch_child_in_background()

        logger.info("Starting MCP server on port %d", port)

        # Built by hand instead of mcp.run(transport="streamable-http") for two
        # reasons, both about teardown:
        #  - uvicorn's capture_signals() replaces our SIGTERM handler for the
        #    whole serve(), so _handle_signal cannot run and llama-server would
        #    be orphaned on every pod delete (hostPID leaves no PID namespace
        #    to reap it). The try/finally below is what tears the child down.
        #  - FastMCP never sets timeout_graceful_shutdown, so uvicorn waits
        #    unboundedly for open connections — and every MCP client holds a
        #    long-lived GET SSE stream, so the kubelet SIGKILLs at the
        #    terminationGracePeriod.
        #
        # ONE budget, split across the two SERIAL legs of this teardown:
        # uvicorn draining open connections, then stop() waiting on the
        # inference child. Spending shutdown_timeout_seconds on each would
        # double a teardown that daemonset-edge.yaml's
        # terminationGracePeriodSeconds is sized from that single figure, and
        # the kubelet's SIGKILL would then leave a hostPID llama-server holding
        # :8080 for the next pod's reaper to find.
        timeout = int((self.config.get("process") or {}).get("shutdown_timeout_seconds", 30))
        drain_timeout = max(1, timeout // 2)
        child_timeout = max(1, timeout - drain_timeout)
        # build_app(), never mcp.streamable_http_app() directly: the bearer
        # gate is an ASGI wrapper around the whole app (client/mcp/server.py),
        # so serving the inner app is how this port silently loses its auth.
        cert_file, key_file = self._tls_cert_and_key()
        server = uvicorn.Server(
            uvicorn.Config(
                build_app(),
                host=mcp.settings.host,
                port=mcp.settings.port,
                log_level=mcp.settings.log_level.lower(),
                timeout_graceful_shutdown=drain_timeout,
                # This node's own leaf, the same pair llama-server is given.
                # uvicorn terminates TLS below the ASGI app, so the /health
                # route and the SSE streams are unaffected.
                ssl_certfile=cert_file,
                ssl_keyfile=key_file,
            )
        )
        try:
            server.run()
        finally:
            # _shutdown BEFORE stop(): the watcher thread reads it, and a child
            # torn down here must not be reported as a crash.
            self._shutdown = True
            self.stop(timeout=child_timeout)

    def _watch_child_in_background(self) -> threading.Thread:
        """Poll the inference child from a daemon thread while the MCP server serves.

        Runs the same _block_on_child supervision the other node shapes run on
        the main thread, so a crash still goes through _exit_reporting (stop,
        flush crash context, ship). sys.exit from a non-main thread only ends
        that thread, so the SystemExit it raises is converted to os._exit.
        """

        def _watch() -> None:
            try:
                self._block_on_child()
            except SystemExit as e:
                code = e.code if isinstance(e.code, int) else 1
                # os._exit skips interpreter teardown, so flush the tee by hand
                # or the child's last lines never leave the container.
                with contextlib.suppress(Exception):
                    sys.stdout.flush()
                os._exit(code)

        thread = threading.Thread(target=_watch, daemon=True, name="child-watch")
        thread.start()
        return thread

    def _handle_signal(self, signum: int, _frame: object) -> None:
        """Graceful shutdown handler.

        Deliberately does not flush or ship: see _exit_reporting's note on the
        terminationGracePeriod budget. Not installed while the MCP server
        serves — uvicorn captures SIGTERM for the duration, and
        _start_mcp_server's finally does this teardown instead.
        """
        logger.info("Received signal %d, shutting down...", signum)
        self._shutdown = True
        self.stop()
        sys.exit(0)

    def stop(self, timeout: float | None = None) -> None:
        """Tear down the inference child, drain its log pump, close the log FD.

        That order is the whole of it, and it is deliberate: terminate the
        child, join the pump so the final lines it wrote land in the file and
        the capture, then close the FD they were written through.

        NOT everything the supervisor started. The telemetry and log-ship
        threads are daemons that end via ``_shutdown`` or interpreter exit, and
        the in-process MCP/planner runtime is unwound by its own caller —
        _exit_reporting calls stop() WITHOUT setting _shutdown, so those loops
        keep running until the process goes.

        The child-handle attributes are read with getattr: _exit_reporting
        funnels every failure path through here, including ones reached on
        objects that tests build with __new__ and only partially populate (the
        same convention _make_child_capture documents).

        ``timeout`` caps the wait on the child and defaults to
        process.shutdown_timeout_seconds. _start_mcp_server passes what is left
        of that budget after uvicorn's graceful drain has taken its half,
        because those two waits are serial and share one
        terminationGracePeriodSeconds.
        """
        if timeout is None:
            timeout = (self.config.get("process") or {}).get("shutdown_timeout_seconds", 30)

        child = getattr(self, "_child_proc", None)
        name = getattr(self, "_child_name", "child")
        if child and child.poll() is None:
            logger.info("Stopping %s (PID %d)", name, child.pid)
            child.terminate()
            try:
                child.wait(timeout=timeout)
            except subprocess.TimeoutExpired:
                logger.warning("%s did not stop, sending SIGKILL", name)
                child.kill()

        # Let the pump drain before closing the FD it writes to. The child's
        # final lines are the ones that explain the crash, and closing under a
        # live writer truncates exactly those.
        pump = getattr(self, "_child_log_thread", None)
        if pump is not None:
            pump.join(timeout=2)
            self._child_log_thread = None

        log_file = getattr(self, "_child_log_file", None)
        # Dropped and closed under suppression: _exit_reporting runs stop()
        # FIRST, so an ENOSPC/EROFS out of the final flush here would skip the
        # crash-context flush and the log ship that follow — the batch that
        # explains the exit. A full or read-only hostPath is exactly the state
        # a crashing node is in.
        self._child_log_file = None
        if log_file is not None:
            with contextlib.suppress(OSError):
                log_file.close()


